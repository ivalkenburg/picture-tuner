#!/usr/bin/env python3
"""Export Picture Tuner's Android resources and store graphics from the Luma Dial source kit.

Sources (canonical, never edited here): branding/luma-dial-source/  (brand.json + svg/)
Outputs:
  app/src/main/res/drawable/ic_launcher_background.xml   adaptive icon background (solid charcoal, 108dp)
  app/src/main/res/drawable/ic_launcher_foreground.xml   adaptive icon foreground (mark, transparent)
  app/src/main/res/drawable/ic_launcher_monochrome.xml   themed-icon layer (Android 13+), single colour
  app/src/main/res/mipmap-anydpi-v26/ic_launcher{,_round}.xml
  app/src/main/res/mipmap-{m..xxxh}dpi/ic_launcher{,_round}.png   legacy icons for API 24-25
  app/src/main/res/drawable/banner.xml                   Android TV launcher banner (320x180dp, wordmark)
  fastlane/metadata/android/en-US/images/{icon,tvBanner,featureGraphic}.png   store graphics

SVG -> VectorDrawable: path data is copied verbatim (VectorDrawable path syntax supports the M/L/H/V/Q/A/Z
commands used). An SVG group "translate(tx ty) scale(s)" becomes an Android <group> with translateX/Y and
scaleX/Y: with pivot 0, Android applies scale then translate, which is exactly the SVG matrix T * S.

Run:  python3 branding/export_android.py          (needs CairoSVG + pillow + numpy for the PNGs/validation)
      python3 branding/export_android.py --check  (validate only, write nothing)
"""
import io
import json
import math
import os
import re
import sys
import xml.etree.ElementTree as ET

import cairosvg
import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KIT = os.path.join(ROOT, "branding", "luma-dial-source")
RES = os.path.join(ROOT, "app", "src", "main", "res")
STORE = os.path.join(ROOT, "fastlane", "metadata", "android", "en-US", "images")
PREVIEW = os.path.join(ROOT, "branding", "android-previews")

BRAND = json.load(open(os.path.join(KIT, "brand.json")))
BG = BRAND["colors"]["background"]
FG = BRAND["colors"]["foreground"]
AMBER = BRAND["colors"]["amber"]

SVG_NS = "{http://www.w3.org/2000/svg}"
LEGACY = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}
# Adaptive icon geometry (dp): 108 canvas, 72 visible, guaranteed-safe circle of 66 diameter.
CANVAS, VISIBLE_R, SAFE_R = 108.0, 36.0, 33.0


# ------------------------------------------------------------------ SVG parsing
TRANSFORM = re.compile(r"^translate\(([-\d.]+)[ ,]+([-\d.]+)\)\s*scale\(([-\d.]+)\)$")


def parse_svg(name):
    """Return (width, height, items). items: ('rect', w, h, fill) | ('group', tx, ty, s, [(fill, d)...])."""
    tree = ET.parse(os.path.join(KIT, "svg", name))
    root = tree.getroot()
    w, h = float(root.get("width")), float(root.get("height"))
    vb = [float(v) for v in root.get("viewBox").split()]
    assert vb == [0, 0, w, h], f"{name}: viewBox must match size"
    items = []
    for el in root:
        tag = el.tag.replace(SVG_NS, "")
        if tag == "title":
            continue
        if tag == "rect":
            assert el.get("x") in (None, "0") and el.get("y") in (None, "0"), f"{name}: offset rect"
            items.append(("rect", float(el.get("width")), float(el.get("height")), el.get("fill")))
        elif tag == "g":
            t = el.get("transform")
            if t:
                m = TRANSFORM.match(t.strip())
                assert m, f"{name}: unsupported transform {t!r}"
                tx, ty, s = (float(v) for v in m.groups())
            else:
                tx, ty, s = 0.0, 0.0, 1.0
            paths = []
            for p in el:
                assert p.tag.replace(SVG_NS, "") == "path", f"{name}: only paths allowed in groups"
                assert p.get("transform") is None and p.get("stroke") is None, f"{name}: path transform/stroke"
                paths.append((p.get("fill") or el.get("fill"), p.get("d")))
            items.append(("group", tx, ty, s, paths))
        else:
            raise AssertionError(f"{name}: unexpected element <{tag}>")
    return w, h, items


# ------------------------------------------------------------------ VectorDrawable writing
def vector_xml(items, vw, vh, wdp, hdp, comment, color_override=None):
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           f"<!-- {comment} Generated by branding/export_android.py from branding/luma-dial-source; do not edit. -->",
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
           f'    android:width="{fmt(wdp)}dp"', f'    android:height="{fmt(hdp)}dp"',
           f'    android:viewportWidth="{fmt(vw)}"', f'    android:viewportHeight="{fmt(vh)}">']
    for it in items:
        if it[0] == "rect":
            _, w, h, fill = it
            out.append(f'    <path android:fillColor="{color_override or fill}" '
                       f'android:pathData="M0,0H{fmt(w)}V{fmt(h)}H0Z" />')
        else:
            _, tx, ty, s, paths = it
            identity = tx == 0 and ty == 0 and s == 1
            ind = "    " if identity else "        "
            if not identity:
                out.append(f'    <group android:translateX="{fmt(tx)}" android:translateY="{fmt(ty)}" '
                           f'android:scaleX="{fmt(s)}" android:scaleY="{fmt(s)}">')
            for fill, d in paths:
                out.append(f'{ind}<path android:fillColor="{color_override or fill}" android:pathData="{d}" />')
            if not identity:
                out.append("    </group>")
    out.append("</vector>")
    return "\n".join(out) + "\n"


def fmt(v):
    return ("%.6f" % v).rstrip("0").rstrip(".")


def vector_to_svg(xml_text):
    """Independent re-reading of a written VectorDrawable as SVG (for render comparison)."""
    A = "{http://schemas.android.com/apk/res/android}"
    root = ET.fromstring(xml_text)
    vw, vh = root.get(A + "viewportWidth"), root.get(A + "viewportHeight")
    body = []

    def walk(el):
        for c in el:
            if c.tag == "group":
                t = (f'translate({c.get(A + "translateX", "0")} {c.get(A + "translateY", "0")}) '
                     f'scale({c.get(A + "scaleX", "1")} {c.get(A + "scaleY", "1")})')
                body.append(f'<g transform="{t}">')
                walk(c)
                body.append("</g>")
            elif c.tag == "path":
                body.append(f'<path fill="{c.get(A + "fillColor")}" d="{c.get(A + "pathData")}"/>')
    walk(root)
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{vw}" height="{vh}" '
            f'viewBox="0 0 {vw} {vh}">' + "".join(body) + "</svg>")


# ------------------------------------------------------------------ rasterizing
def render(svg_text_or_name, w, h):
    if svg_text_or_name.endswith(".svg") and "<svg" not in svg_text_or_name:
        data = open(os.path.join(KIT, "svg", svg_text_or_name), "rb").read()
    else:
        data = svg_text_or_name.encode()
    png = cairosvg.svg2png(bytestring=data, output_width=w, output_height=h)
    return Image.open(io.BytesIO(png)).convert("RGBA")


def svg_inner(name):
    text = open(os.path.join(KIT, "svg", name)).read()
    text = re.sub(r"<title>.*?</title>", "", text, flags=re.S)
    return re.sub(r"^.*?<svg[^>]*>", "", text, count=1, flags=re.S).rsplit("</svg>", 1)[0]


def feature_graphic_svg():
    """1024x500 store feature graphic: the horizontal logo centred on charcoal (logo is 1600x448)."""
    lw = 860.0
    lh = lw * 448 / 1600
    x, y = (1024 - lw) / 2, (500 - lh) / 2
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="500" viewBox="0 0 1024 500">'
            f'<rect width="1024" height="500" fill="{BG}"/>'
            f'<svg x="{fmt(x)}" y="{fmt(y)}" width="{fmt(lw)}" height="{fmt(lh)}" viewBox="0 0 1600 448">'
            f'{svg_inner("logo-horizontal.svg")}</svg></svg>')


def round_legacy(img):
    """Legacy round icon: circle-masked square composition, anti-aliased via 4x supersampled mask."""
    n = img.size[0]
    big = 4 * n
    yy, xx = np.mgrid[0:big, 0:big] + 0.5
    mask = ((xx - big / 2) ** 2 + (yy - big / 2) ** 2 <= (big / 2) ** 2).astype(np.uint8) * 255
    mask = Image.fromarray(mask, "L").resize((n, n), Image.LANCZOS)
    out = img.copy()
    out.putalpha(Image.fromarray(np.minimum(np.array(img)[..., 3], np.array(mask)), "L"))
    return out


# ------------------------------------------------------------------ validation helpers
def rgba(img):
    return np.array(img).astype(int)


def alpha_at(a, x, y):
    return a[int(y), int(x), 3]


def check(cond, msg, failures):
    print(("  ok   " if cond else "  FAIL ") + msg)
    if not cond:
        failures.append(msg)


def mark_points(tx, ty, s, px_per_unit):
    """Probe points (canvas px) derived from brand.json geometry, for transparency/opacity checks."""
    m = BRAND["mark"]
    cx, cy = m["center"]

    def P(r, deg):
        a = math.radians(deg)
        return ((tx + s * (cx + r * math.cos(a))) * px_per_unit, (ty + s * (cy + r * math.sin(a))) * px_per_unit)
    rc = m["ring_centerline_radius"]
    # The tick crosses the gap at -45deg; at the ring centreline the clear parts of the gap are roughly
    # -62..-52deg and -38..-28deg (ring end caps r=24, tick half-width 22), so probe -57 and -33.
    return {
        "center square (opaque)": P(0, 0),
        "ring body at 180deg (opaque)": P(rc, 180),
        "ring body at 90deg (opaque)": P(rc, 90),
        "interior between square and ring, 135deg r=100 (transparent)": P(100, 135),
        "interior between square and ring, 0deg r=100 (transparent)": P(100, 0),
        "upper-right gap at -57deg (transparent)": P(rc, -57),
        "upper-right gap at -33deg (transparent)": P(rc, -33),
        "tick middle (opaque, amber)": P((m["tick_start_radius"] + m["tick_end_radius"]) / 2, m["tick_angle_degrees"]),
    }


# ------------------------------------------------------------------ main
def main():
    only_check = "--check" in sys.argv
    failures = []
    written = []

    def write(path, data, binary=False):
        if only_check:
            return
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "wb" if binary else "w") as f:
            f.write(data)
        written.append(os.path.relpath(path, ROOT))

    # --- vectors ---------------------------------------------------------
    fw, fh, fg_items = parse_svg("icon-adaptive-foreground.svg")
    bw, bh, bg_items = parse_svg("icon-adaptive-background.svg")
    _, _, mono_items = parse_svg("mark-mono-light.svg")
    tw, th, banner_items = parse_svg("tv-banner.svg")
    assert (fw, fh, bw, bh) == (108, 108, 108, 108)
    assert len(fg_items) == 1 and len(fg_items[0][4]) == 3, "foreground must be the 3-path mark"
    gtx, gty, gs = fg_items[0][1:4]
    mono_paths = mono_items[0][4]
    assert [d for _, d in mono_paths] == [d for _, d in fg_items[0][4]], "mono geometry must equal the mark"
    mono_placed = [("group", gtx, gty, gs, mono_paths)]

    vectors = {
        "drawable/ic_launcher_background.xml":
            vector_xml(bg_items, 108, 108, 108, 108, "Adaptive icon background: solid charcoal, full bleed."),
        "drawable/ic_launcher_foreground.xml":
            vector_xml(fg_items, 108, 108, 108, 108, "Adaptive icon foreground: Luma Dial mark, transparent around it."),
        "drawable/ic_launcher_monochrome.xml":
            vector_xml(mono_placed, 108, 108, 108, 108,
                       "Themed (monochrome) icon layer, Android 13+: alpha only, colour is ignored.", "#FFFFFFFF"),
        "drawable/banner.xml":
            vector_xml(banner_items, tw, th, 320, 180, "Android TV launcher banner, 16:9 (320x180dp)."),
    }
    adaptive = ('<?xml version="1.0" encoding="utf-8"?>\n'
                "<!-- Generated by branding/export_android.py; do not edit. -->\n"
                '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
                '    <background android:drawable="@drawable/ic_launcher_background" />\n'
                '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
                '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n'
                "</adaptive-icon>\n")
    for rel, text in vectors.items():
        write(os.path.join(RES, rel), text)
    for name in ("ic_launcher", "ic_launcher_round"):
        write(os.path.join(RES, "mipmap-anydpi-v26", name + ".xml"), adaptive)

    # --- rasters ---------------------------------------------------------
    square = {}
    for dens, px in LEGACY.items():
        img = render("icon-square.svg", px, px)
        square[dens] = img
        for name, im in (("ic_launcher", img), ("ic_launcher_round", round_legacy(img))):
            buf = io.BytesIO()
            im.save(buf, "PNG")
            write(os.path.join(RES, f"mipmap-{dens}", name + ".png"), buf.getvalue(), binary=True)
    store = {
        "icon.png": (render("icon-square.svg", 512, 512), "RGBA"),          # Play: 512x512 32-bit PNG
        "tvBanner.png": (render("tv-banner.svg", 1280, 720), "RGB"),        # Play: 1280x720, no alpha
        "featureGraphic.png": (render(feature_graphic_svg(), 1024, 500), "RGB"),  # Play: 1024x500, no alpha
    }
    for name, (img, mode) in store.items():
        buf = io.BytesIO()
        img.convert(mode).save(buf, "PNG")
        write(os.path.join(STORE, name), buf.getvalue(), binary=True)

    # --- validation ------------------------------------------------------
    print("Validation")
    # 1. converted vectors render like their SVG sources
    pairs = [("drawable/ic_launcher_foreground.xml", "icon-adaptive-foreground.svg", 432, 432),
             ("drawable/ic_launcher_background.xml", "icon-adaptive-background.svg", 432, 432),
             ("drawable/banner.xml", "tv-banner.svg", 1280, 720)]
    for rel, src, w, h in pairs:
        a = rgba(render(vector_to_svg(vectors[rel]), w, h))
        b = rgba(render(src, w, h))
        diff = np.abs(a - b).max()
        check(diff <= 1, f"{rel} renders like {src} at {w}x{h} (max channel diff {diff})", failures)
    mono = rgba(render(vector_to_svg(vectors["drawable/ic_launcher_monochrome.xml"]), 432, 432))[..., 3]
    fga = rgba(render("icon-adaptive-foreground.svg", 432, 432))[..., 3]
    check(np.abs(mono - fga).max() <= 1, "monochrome layer has exactly the foreground's shape (alpha)", failures)

    # 2. adaptive foreground: transparency, opacity, palette and safe zone
    ppu = 10  # px per dp
    fg = rgba(render("icon-adaptive-foreground.svg", 1080, 1080))
    for label, (x, y) in mark_points(gtx, gty, gs, ppu).items():
        a = alpha_at(fg, x, y)
        want_opaque = "opaque" in label
        check((a == 255) if want_opaque else (a == 0), f"foreground {label}: alpha {a}", failures)
    for (x, y) in [(2, 2), (1077, 2), (2, 1077), (1077, 1077)]:
        check(fg[y, x, 3] == 0, f"foreground corner ({x},{y}) transparent", failures)
    pts = mark_points(gtx, gty, gs, ppu)
    sq = fg[int(pts["center square (opaque)"][1]), int(pts["center square (opaque)"][0])]
    tk = fg[int(pts["tick middle (opaque, amber)"][1]), int(pts["tick middle (opaque, amber)"][0])]
    check("#%02X%02X%02X" % tuple(sq[:3]) == FG, f"centre square colour {FG}", failures)
    check("#%02X%02X%02X" % tuple(tk[:3]) == AMBER, f"tick colour {AMBER}", failures)
    yy, xx = np.mgrid[0:1080, 0:1080] + 0.5
    r = np.hypot(xx - 540, yy - 540) / ppu
    extent = r[fg[..., 3] > 0].max()
    check(extent <= SAFE_R, f"foreground fits the {SAFE_R:g}dp safe circle (furthest pixel {extent:.2f}dp)", failures)
    bgimg = rgba(render("icon-adaptive-background.svg", 108, 108))
    check((bgimg[..., 3] == 255).all() and (bgimg[..., :3] == [int(BG[i:i + 2], 16) for i in (1, 3, 5)]).all(),
          f"background is opaque solid {BG}, full bleed", failures)

    # 3. masks: foreground never cropped by common launcher masks (defined on the 72dp visible area)
    u = (xx - 540) / ppu, (yy - 540) / ppu
    masks = {
        "circle": np.hypot(*u) <= VISIBLE_R,
        "squircle": (np.abs(u[0]) ** 4 + np.abs(u[1]) ** 4) <= VISIBLE_R ** 4,
        "rounded square": rounded_rect(u, VISIBLE_R, 12),
        "teardrop": teardrop(u),
    }
    comp = Image.alpha_composite(Image.fromarray(np.uint8(bgimg_full(1080))), Image.fromarray(np.uint8(fg)))
    tiles = []
    for name, m in masks.items():
        cropped = int(((fg[..., 3] > 0) & ~m).sum())
        check(cropped == 0, f"mask '{name}': {cropped} foreground pixels cropped", failures)
        t = np.array(comp).copy()
        t[..., 3] = np.where(m, 255, 0)
        tile = Image.fromarray(t).crop((180, 180, 900, 900)).resize((180, 180), Image.LANCZOS)
        tiles.append(tile)

    # 4. sizes / modes of written rasters
    for dens, px in LEGACY.items():
        check(square[dens].size == (px, px), f"mipmap-{dens} icons are {px}x{px}", failures)
    for name, (img, mode) in store.items():
        check(True, f"store {name}: {img.size[0]}x{img.size[1]} {mode}", failures)
    check(store["tvBanner.png"][0].size == (1280, 720) and store["featureGraphic.png"][0].size == (1024, 500)
          and store["icon.png"][0].size == (512, 512), "store graphics have Play-required sizes", failures)

    # 5. banner lettering at launcher size: the wordmark must stay resolvable at 320x180 px (mdpi)
    small = rgba(render(vector_to_svg(vectors["drawable/banner.xml"]), 320, 180))
    word = small[:, 376 // 4:, :3]
    lit = (np.abs(word - [int(FG[i:i + 2], 16) for i in (1, 3, 5)]).sum(axis=2) < 60)
    rows = np.where(lit.any(axis=1))[0]
    cap = rows.max() - rows.min() + 1 if len(rows) else 0
    check(cap >= 20, f"banner wordmark is {cap}px tall at 320x180 (>= 20px for legibility)", failures)

    # previews for visual comparison
    if not only_check:
        os.makedirs(PREVIEW, exist_ok=True)
        sheet = Image.new("RGBA", (180 * 4 + 50, 220), (40, 42, 48, 255))
        for i, t in enumerate(tiles):
            sheet.alpha_composite(t, (10 + i * 190, 30))
        sheet.save(os.path.join(PREVIEW, "adaptive-masks.png"))
        Image.fromarray(np.uint8(small)).save(os.path.join(PREVIEW, "banner-320x180.png"))
        render(vector_to_svg(vectors["drawable/banner.xml"]), 640, 360).save(os.path.join(PREVIEW, "banner-640x360.png"))
        written.extend(os.path.relpath(os.path.join(PREVIEW, f), ROOT)
                       for f in ("adaptive-masks.png", "banner-320x180.png", "banner-640x360.png"))

    if written:
        print("Written:\n  " + "\n  ".join(written))
    if failures:
        print(f"{len(failures)} check(s) FAILED")
        sys.exit(1)
    print("All checks passed.")


def bgimg_full(n):
    c = [int(BG[i:i + 2], 16) for i in (1, 3, 5)] + [255]
    return np.tile(np.array(c, dtype=np.uint8), (n, n, 1))


def rounded_rect(u, half, rad):
    x, y = np.abs(u[0]), np.abs(u[1])
    inside = (x <= half) & (y <= half)
    corner = (x > half - rad) & (y > half - rad)
    return inside & (~corner | (np.hypot(x - (half - rad), y - (half - rad)) <= rad))


def teardrop(u):
    """Circle with a square bottom-right corner (the classic teardrop launcher shape)."""
    x, y = u
    circle = np.hypot(x, y) <= VISIBLE_R
    br = (x >= 0) & (y >= 0) & (x <= VISIBLE_R) & (y <= VISIBLE_R)
    return circle | br


if __name__ == "__main__":
    main()
